"""Настройка конфигурации приложения Теги.

Этот модуль содержит настройки конфигурации приложения Теги.
"""

from django.apps import AppConfig


class TagsConfig(AppConfig):
    """Класс конфигурации для приложения Теги.

    Определяет настройки приложения Теги.
    Описывает имя приложения и отображаемое имя.
    """
    name = 'tags'
    verbose_name = 'Теги'
